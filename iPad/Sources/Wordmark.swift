/// A view that shows the wordmark, fitted to its height and aligned to the left.
final class WordmarkView: UIView {
    /// Width the wordmark takes up at a given height.
    static func width(forHeight h: CGFloat) -> CGFloat {
        return ceil(h * Wordmark.size.width / Wordmark.size.height)
    }

    override init(frame: CGRect) {
        super.init(frame: frame)
        backgroundColor = UIColor.clear
        isOpaque = false
        contentMode = .redraw
        isUserInteractionEnabled = false
        isAccessibilityElement = true
        accessibilityLabel = "SwiftCel"
    }

    required init?(coder: NSCoder) {
        fatalError("init(coder:) is not used")
    }

    override func draw(_ rect: CGRect) {
        guard let ctx = UIGraphicsGetCurrentContext() else { return }
        let scale = min(bounds.height / Wordmark.size.height, bounds.width / Wordmark.size.width)
        let h = Wordmark.size.height * scale
        ctx.translateBy(x: 0, y: (bounds.height - h) / 2)
        ctx.scaleBy(x: scale, y: scale)
        ctx.addPath(Wordmark.path)
        ctx.setFillColor(Theme.text.cgColor)
        ctx.fillPath(using: .winding)
    }
}
